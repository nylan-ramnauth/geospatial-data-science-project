# -----------------------------
# 4) READ GENERATORS
# -----------------------------
cat("Reading generators...\n")
gen_ll <- st_read(GENERATORS_GPKG, layer = GEN_LAYER, quiet = TRUE) %>%
  st_make_valid() %>%
  st_transform(4326)

col_name  <- if ("plant_name"   %in% names(gen_ll)) "plant_name"   else if ("name"  %in% names(gen_ll)) "name"  else NA_character_
col_fuel  <- if ("fuel_or_tech" %in% names(gen_ll)) "fuel_or_tech" else if ("fuel"  %in% names(gen_ll)) "fuel"  else NA_character_
col_stat  <- if ("status"       %in% names(gen_ll)) "status"       else NA_character_
col_cap   <- if ("capacity_mw"  %in% names(gen_ll)) "capacity_mw"  else NA_character_
col_owner <- if ("owner"        %in% names(gen_ll)) "owner"        else NA_character_
col_tech  <- if ("technology"   %in% names(gen_ll)) "technology"   else NA_character_
col_start <- if ("start_year"   %in% names(gen_ll)) "start_year"   else NA_character_
col_type  <- if ("type"         %in% names(gen_ll)) "type"         else NA_character_

gen_ll$fuel_val <- if (!is.na(col_fuel)) as.character(gen_ll[[col_fuel]]) else NA_character_
gen_ll$mk_col   <- fuel_color(gen_ll$fuel_val)

gen_ll$popup_html <- vapply(seq_len(nrow(gen_ll)), function(i) {
  r     <- gen_ll[i, ]
  nm    <- if (!is.na(col_name))  as.character(r[[col_name]])  else "Power plant"
  fuel  <- if (!is.na(col_fuel))  as.character(r[[col_fuel]])  else "Unknown"
  stat  <- if (!is.na(col_stat))  as.character(r[[col_stat]])  else "Unknown"
  cap   <- if (!is.na(col_cap))   suppressWarnings(as.numeric(r[[col_cap]])) else NA_real_
  owner <- if (!is.na(col_owner)) as.character(r[[col_owner]]) else NA_character_
  tech  <- if (!is.na(col_tech))  as.character(r[[col_tech]])  else NA_character_
  sy    <- if (!is.na(col_start)) as.character(r[[col_start]]) else NA_character_
  typ   <- if (!is.na(col_type))  as.character(r[[col_type]])  else NA_character_

  dot <- fuel_color(fuel)

  extra_lines <- character(0)
  if (!is.na(typ)   && nzchar(typ))   extra_lines <- c(extra_lines, paste0("<b>Type:</b> ",        htmlEscape(typ)))
  if (!is.na(owner) && nzchar(owner)) extra_lines <- c(extra_lines, paste0("<b>Owner:</b> ",       htmlEscape(owner)))
  if (!is.na(tech)  && nzchar(tech))  extra_lines <- c(extra_lines, paste0("<b>Technology:</b> ",  htmlEscape(tech)))
  if (!is.na(sy)    && nzchar(sy))    extra_lines <- c(extra_lines, paste0("<b>Start year:</b> ",  htmlEscape(sy)))

  paste0(
    "<div style='font-family: system-ui,-apple-system,Segoe UI,Roboto,Arial; font-size:14px; line-height:1.45; min-width:260px;'>",
    "<div style='font-size:18px; font-weight:800; letter-spacing:1px; text-transform:uppercase; margin-bottom:10px;'>",
    htmlEscape(nm),
    "</div>",
    "<div style='margin-bottom:6px;'>",
    "<b>Fuel/Tech:</b> ",
    "<span style='display:inline-block;width:10px;height:10px;border-radius:50%;background:", dot, ";margin:0 8px 0 6px;'></span>",
    htmlEscape(fuel),
    "</div>",
    "<div style='margin-bottom:6px;'><b>Status:</b> ", htmlEscape(stat), "</div>",
    "<div style='margin-bottom:10px;'><b>Capacity:</b> ",
    ifelse(is.na(cap), "NA", paste0(fmt_num(cap, 1), " MW")),
    "</div>",
    if (length(extra_lines) > 0) paste0(paste0(extra_lines, collapse = "<br>"), "<br>") else "",
    "</div>"
  )
}, character(1))

