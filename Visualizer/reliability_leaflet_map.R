# -----------------------------
# HELPERS
# -----------------------------
fmt_num <- function(x, digits = 1) {
  ifelse(is.na(x), "NA", formatC(as.numeric(x), format = "f", digits = digits))
}

fmt_int <- function(x) {
  x <- suppressWarnings(as.numeric(x))
  ifelse(is.na(x), "NA", formatC(x, format = "d", big.mark = ","))
}

s <- function(x) {
  x <- as.character(x)
  ifelse(is.na(x) | !nzchar(x), "NA", htmlEscape(x))
}

fuel_color <- function(fuel) {
  f <- tolower(trimws(as.character(fuel)))
  f[is.na(f) | f == ""] <- "unknown"

  dplyr::case_when(
    grepl("coal", f)                      ~ "#1F1F1F",
    grepl("gas", f)                       ~ "#4d4d4d",
    grepl("oil|diesel", f)                ~ "#8C510A",
    grepl("nuclear", f)                   ~ "#7B3294",
    grepl("hydro", f)                     ~ "#2C7FB8",
    grepl("wind", f)                      ~ "#41AB5D",
    grepl("solar", f)                     ~ "#00A087",
    grepl("bio|biomass|biogas|waste", f)  ~ "#6B8E23",
    TRUE                                  ~ "#6E6E6E"
  )
}

# -----------------------------
# 1) READ RELIABILITY PARQUET
# -----------------------------
if (!file.exists(RELIABILITY_PARQUET)) {
  stop("Stage 3b output not found: ", RELIABILITY_PARQUET,
       "\nRun Visualizer/reliability_panel_build_yearlykeep.R first.")
}
cat("Reading reliability parquet...\n")
rel <- read_parquet(RELIABILITY_PARQUET)

cat("Computing annual dark-day counts from states...\n")
dark_annual <- read_parquet(
  STATES_PARQUET,
  col_select = c("settlement_id", "dark_day")
) %>%
  group_by(settlement_id) %>%
  summarise(n_dark_days_annual = sum(dark_day, na.rm = TRUE), .groups = "drop") %>%
  mutate(settlement_id = as.character(settlement_id))

# -----------------------------
# 2) READ SETTLEMENT GEOMETRIES
# -----------------------------
cat("Reading settlement geometries...\n")
sett <- st_read(SETT_SIMPL_GPKG, quiet = TRUE) %>%
  st_make_valid()

# Left-join reliability metrics onto settlement geometry (coerce key to character)
map_sf <- sett %>%
  mutate(settlement_id = as.character(settlement_id)) %>%
  left_join(
    rel %>%
      mutate(settlement_id = as.character(settlement_id)) %>%
      select(settlement_id, uptime, dark_share, mean_p_lit,
             n_days_obs, cv_p_lit, mean_coverage),
    by = "settlement_id"
  ) %>%
  left_join(dark_annual, by = "settlement_id") %>%
  st_transform(4326)

# -----------------------------
# SETTLEMENT POPUP
# -----------------------------
popup_settlement <- function(df) {
  paste0(
    "<div style='font-size:13px; line-height:1.5; min-width:240px;'>",

    "<div style='font-size:15px; font-weight:bold; margin-bottom:6px;'>",
    s(df$village_name),
    "</div>",

    "<b>Yearly uptime:</b> ",           fmt_num(df$uptime, 3),         "<br>",
    "<b>Dark share:</b> ",              fmt_num(df$dark_share, 3),      "<br>",
    "<b>CV radiance (volatility):</b> ", fmt_num(df$cv_p_lit, 3),      "<br>",
    "<b>Days observed:</b> ",           fmt_int(df$n_days_obs),         "<br>",
    "<b>Dark days (full year):</b> ",   fmt_int(df$n_dark_days_annual), "<br>",
    "<b>Mean p<sub>lit</sub>:</b> ",    fmt_num(df$mean_p_lit, 3),      "<br>",
    "<b>Mean pixel coverage:</b> ",     fmt_num(df$mean_coverage, 2),   "<br><br>",

    "<b>Population:</b> ",              fmt_int(df$population),         "<br>",
    "<b>Building density:</b> ",        s(df$building_density_percent), "<br>",
    "<b>Demand (kWh/day):</b> ",        fmt_num(df$demand, 1),          "<br><br>",

    "<b>Province:</b> ",  s(df$admin_cgaz_1), "<br>",
    "<b>District:</b> ",  s(df$admin_cgaz_2),

    "</div>"
  )
}

cat("Building settlement popups...\n")
map_sf$popup_html <- vapply(seq_len(nrow(map_sf)),
  function(i) popup_settlement(map_sf[i, ]), character(1))

