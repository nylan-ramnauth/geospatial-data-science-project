# -----------------------------
# 6) BUILD LEAFLET MAP
# -----------------------------
cat("Building Leaflet map...\n")

pal <- leaflet::colorNumeric(
  palette  = colorRampPalette(c("#5e0000", "#b30000", "#e34a33", "#fc8d59", "#fed976"))(256),
  domain   = c(0, 1),
  na.color = "#e0e0e0"
)

GRID_COL <- "#08306B"

map <- leaflet(options = leafletOptions(preferCanvas = TRUE)) %>%

  addProviderTiles(providers$CartoDB.Positron,        group = "Basemap (Light)") %>%
  addProviderTiles(providers$Esri.WorldImagery,        group = "Satellite") %>%
  addProviderTiles(providers$CartoDB.PositronOnlyLabels, group = "Labels") %>%

  addPolygons(
    data         = map_sf,
    group        = "Settlements (yearly uptime)",
    fillColor    = ~pal(uptime),
    fillOpacity  = 0.75,
    color        = NA,
    weight       = 0,
    smoothFactor = 0.2,
    popup        = ~popup_html
  ) %>%

  addPolylines(
    data         = grid_sa,
    group        = "Grid (South Africa)",
    color        = GRID_COL,
    weight       = 1.0,
    opacity      = 0.55,
    smoothFactor = 1
  ) %>%

  addPolylines(
    data    = sa0,
    group   = "South Africa border",
    color   = "#000000",
    weight  = 1.2,
    opacity = 0.85
  ) %>%

  addCircleMarkers(
    data        = gen_ll,
    group       = "Power plants",
    radius      = 4.5,
    stroke      = TRUE,
    weight      = 1.2,
    opacity     = 0.9,
    color       = "#FFFFFF",
    fillOpacity = 0.95,
    fillColor   = ~mk_col,
    popup       = ~popup_html
  ) %>%

  addLayersControl(
    baseGroups = c("Basemap (Light)", "Satellite"),
    overlayGroups = c(
      "Labels",
      "Settlements (yearly uptime)",
      "Grid (South Africa)",
      "South Africa border",
      "Power plants"
    ),
    options = layersControlOptions(collapsed = FALSE)
  ) %>%

  addLegend(
    position = "topright",
    pal      = pal,
    values   = map_sf$uptime,
    title    = "Yearly uptime",
    opacity  = 1
  ) %>%

  setView(lng = 24.5, lat = -29.0, zoom = 5)

# -----------------------------
# 7) SAVE HTML
# -----------------------------
cat("Saving HTML...\n")
htmlwidgets::saveWidget(map, OUT_HTML, selfcontained = TRUE)
cat("Saved:", OUT_HTML, "\n")
