BASE_PATH <- here::here()

RELIABILITY_PARQUET <- file.path(BASE_PATH, "Map Data", "reliability_outputs_blackmarbler",
  "settlement_reliability_yearly_strict_yearlykeep_postdoe.parquet")

STATES_PARQUET <- file.path(BASE_PATH, "Map Data", "reliability_outputs_blackmarbler",
  "settlement_day_states_strict_yearlykeep.parquet")

SETT_SIMPL_GPKG <- file.path(BASE_PATH, "Map Data", "Settlements", "GPKG",
  "south_africa_dre_atlas_settlements_simplified_full_col.gpkg")

GENERATORS_GPKG <- file.path(BASE_PATH, "Map Data", "Generators Data", "generators_outputs",
  "south_africa_power_plants.gpkg")
GEN_LAYER <- "generators_sa"

BOUNDARIES_GPKG <- file.path(BASE_PATH, "Map Data", "Boundaries", "boundaries_outputs",
  "south_africa_admin_boundaries_GADM.gpkg")
BND_LAYER_ADMIN0 <- "admin0_country"

GRID_GPKG <- file.path(BASE_PATH, "Map Data", "Grid Data", "electricitygrid_Africa_JRC",
  "output_folder", "electricity_grid_south_africa.gpkg")
GRID_LAYER <- "grid_sa"

